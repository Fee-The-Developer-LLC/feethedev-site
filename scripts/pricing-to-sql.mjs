#!/usr/bin/env node
/**
 * Writes a Supabase migration that makes `public.service_catalog` match
 * `lib/pricing-catalog.json`. Regenerate after every catalog change:
 *
 *   npm run pricing:sql -- supabase/migrations/<timestamp>_service_catalog_<name>.sql
 *
 * The first run (pricing v2) also widens the table's checks for flat prices,
 * yearly billing and pricing lines, and renames four legacy slugs that had
 * drifted from the site. Every statement is safe to run more than once.
 */
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
import { CATALOG_PATH, validateCatalog } from './sync-pricing.mjs';

/** Slugs the 2026-10-01 seed used that differ from the site and Stripe. */
const LEGACY_SLUGS = {
  'google-business-profile-setup-and-verification-support':
    'google-business-profile-setup',
  'contact-category-location-and-service-area-alignment':
    'contact-category-location-alignment',
  'google-workspace-and-business-email-setup':
    'google-workspace-and-business-email',
  'public-data-monitoring-and-change-alerts':
    'public-data-monitoring-and-alerts',
};

const q = (value) => `'${String(value).replaceAll("'", "''")}'`;

export function catalogToSql(catalog) {
  const problems = validateCatalog(catalog);
  if (problems.length)
    throw new Error(`Catalog is invalid:\n- ${problems.join('\n- ')}`);
  const lines = ['starter', 'websites', 'systems', 'presence', 'care'];
  const source = `lib/pricing-catalog.json@${catalog.version}`;

  const rows = [...catalog.items]
    .sort((a, b) => a.sortOrder - b.sortOrder)
    .map(
      (i) =>
        `  (${[
          q(i.slug),
          q(i.name),
          q(i.featured && i.line !== 'starter' ? 'package' : 'service'),
          q(i.line),
          i.amountCents,
          q(i.interval),
          q(i.priceMode === 'flat' ? 'Flat' : 'Starting at'),
          q(i.scopeNote),
          i.sortOrder,
          q(source),
          i.status === 'active' ? 'true' : 'false',
        ].join(', ')})`,
    );

  const activeSlugs = catalog.items
    .filter((i) => i.status === 'active')
    .map((i) => q(i.slug));

  return `-- Generated by scripts/pricing-to-sql.mjs from lib/pricing-catalog.json (${catalog.version}).
-- Do not edit by hand: change the catalog and regenerate.

-- Allow flat prices, yearly billing and pricing lines.
alter table public.service_catalog drop constraint if exists service_catalog_billing_interval_check;
alter table public.service_catalog add constraint service_catalog_billing_interval_check
  check (billing_interval in ('one_time', 'month', 'year'));
alter table public.service_catalog drop constraint if exists service_catalog_price_qualifier_check;
alter table public.service_catalog add constraint service_catalog_price_qualifier_check
  check (price_qualifier in ('Starting at', 'Flat'));
alter table public.service_catalog add column if not exists line text;
alter table public.service_catalog drop constraint if exists service_catalog_line_check;
alter table public.service_catalog add constraint service_catalog_line_check
  check (line is null or line in (${lines.map(q).join(', ')}));
alter table public.service_catalog alter column source_ref set default ${q('lib/pricing-catalog.json')};

-- Align legacy slugs with the site and Stripe.
${Object.entries(LEGACY_SLUGS)
  .map(
    ([from, to]) =>
      `update public.service_catalog set slug = ${q(to)}\n  where slug = ${q(from)}\n  and not exists (select 1 from public.service_catalog where slug = ${q(to)});`,
  )
  .join('\n')}

-- Free the unique sort_order values, then upsert the catalog.
update public.service_catalog set sort_order = sort_order + 100000 where sort_order < 100000;

insert into public.service_catalog
  (slug, name, category, line, amount_cents, billing_interval, price_qualifier, scope_note, sort_order, source_ref, active)
values
${rows.join(',\n')}
on conflict (slug) do update set
  name = excluded.name,
  category = excluded.category,
  line = excluded.line,
  amount_cents = excluded.amount_cents,
  billing_interval = excluded.billing_interval,
  price_qualifier = excluded.price_qualifier,
  scope_note = excluded.scope_note,
  sort_order = excluded.sort_order,
  source_ref = excluded.source_ref,
  active = excluded.active,
  updated_at = now();

-- Anything no longer in the catalog stops showing.
update public.service_catalog set active = false, updated_at = now()
  where slug not in (${activeSlugs.join(', ')})
  and active;
`;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const out = process.argv[2];
  const catalog = JSON.parse(fs.readFileSync(CATALOG_PATH, 'utf8'));
  const sql = catalogToSql(catalog);
  if (out) {
    fs.writeFileSync(out, sql);
    console.log(`wrote ${out}`);
  } else {
    process.stdout.write(sql);
  }
}
